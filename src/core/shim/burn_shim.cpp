extern "C" void rei_m92_reset(void);
extern "C" void rei_core_reset(void)
{
	if (strcmp(s_board, "M92") == 0) {
		rei_m92_reset();
	} else if (s_is_m107 && rei_pipelined) {
		rei_m107_reset(); // (pipeline line count and events restart too)
		rei_defer_reset();
	} else {
		// Other boards: like FBNeo, hold the driver's "reset" input for the next frame (the driver frame performs the reset)
		s_reset_pending = 1;
		rei_defer_reset();
	}
	REI_SH(rei_stop) = 0;
}

