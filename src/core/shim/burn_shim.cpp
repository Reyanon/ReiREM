	rei_render_threaded = (cfg->pipelined && cfg->render_threaded) ? 1 : 0;
	rei_index_out = (cfg->pipelined && cfg->index_out) ? 1 : 0;
	rei_out_pal = NULL;
	rei_ge_layers = (rei_index_out && cfg->ge_layers) ? 1 : 0;
	rei_ge_ref = 0;
	rei_ge_sprites = (rei_ge_layers && rei_render_threaded && cfg->ge_sprites) ? 1 : 0;
	// 1..240 lines (was only 16/64/128, anything else silently 32)
