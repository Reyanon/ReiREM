// load.cpp: BurnLoadRom (nGap only, the range d_m92.cpp uses)

INT32 BurnLoadRomExt(UINT8 *Dest, INT32 i, INT32 nGap, INT32 nFlags)
{
	if (BurnExtLoadRom == NULL)
		return 1;
	if (nFlags != 0) {
		bprintf(PRINT_ERROR, _T("BurnLoadRomExt: unsupported flags 0x%x\n"), nFlags);
		return 1;
	}

	struct BurnRomInfo ri;
	ri.nType = 0;
	ri.nLen = 0;
	BurnDrvGetRomInfo(&ri, i);
	if (ri.nType == 0)
		return 0;
	INT32 nLen = ri.nLen;
	if (nLen <= 0)
		return 1;

	if (nGap > 1) {
		UINT8 *Load = (UINT8 *)BurnMalloc(nLen);
		if (Load == NULL)
			return 1;
		memset(Load, 0, nLen);
		INT32 nLoadLen = 0;
		if (BurnExtLoadRom(Load, &nLoadLen, i) != 0) {
			BurnFree(Load);
			return 1;
		}
		if (nLoadLen < 0) nLoadLen = 0;
		if (nLoadLen > nLen) nLoadLen = nLen;
		for (INT32 n = 0, z = 0; n < nLoadLen; n++, z += nGap)
			Dest[z] = Load[n];
		BurnFree(Load);
	} else {
		if (BurnExtLoadRom(Dest, NULL, i) != 0)
			return 1;
	}
	return 0;
}

INT32 BurnLoadRom(UINT8 *Dest, INT32 i, INT32 nGap)
{
	const INT32 r = BurnLoadRomExt(Dest, i, nGap, 0);
	if (s_progress && s_rom_total > 0) { // loading progress: ROM bytes read (0-90% of driver init)
		struct BurnRomInfo ri;
		ri.nLen = 0;
		BurnDrvGetRomInfo(&ri, i);
		s_rom_done += ri.nLen > 0 ? ri.nLen : 0;
		s_progress((int)(s_rom_done * 900 / s_rom_total), s_progress_user);
	}
	return r;
}

