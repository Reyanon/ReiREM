// Deterministic auto input (harness --autoplay and Vita REI_AUTOPLAY builds use the same sequence)
// Boot (RAM/ROM test) takes ~900 frames, so after the title: coin → 1P start → walk right while attacking
static int s_autoplay_char;
extern "C" void rei_core_set_autoplay_char(int ch)
{
	s_autoplay_char = (ch >= 1 && ch <= 4) ? ch : 0;
}

extern "C" void rei_core_autoplay(int frame)
{
	rei_core_set_input(REI_IN_P1_COIN, frame >= 1000 && frame < 1010);
	rei_core_set_input(REI_IN_P1_START, frame >= 1120 && frame < 1130);
	if (s_autoplay_char && frame >= 1200 && frame < 1400) { // select screen: right (n-1) times (4 frames every 20), then attack
		const int k = (frame - 1200) / 20, on = (frame - 1200) % 20 < 4;
		rei_core_set_input(REI_IN_P1_RIGHT, on && k < s_autoplay_char - 1);
		rei_core_set_input(REI_IN_P1_B1, on && k == 5);
		return;
	}
	if (frame >= 1400) {
		int t = frame % 240;
		rei_core_set_input(REI_IN_P1_RIGHT, t < 160);
		rei_core_set_input(REI_IN_P1_LEFT, t >= 200);
		rei_core_set_input(REI_IN_P1_UP, t >= 160 && t < 180);
		rei_core_set_input(REI_IN_P1_DOWN, t >= 180 && t < 200);
		rei_core_set_input(REI_IN_P1_B1, (frame % 16) < 4);
		rei_core_set_input(REI_IN_P1_B2, (frame % 120) < 3);
	}
}

