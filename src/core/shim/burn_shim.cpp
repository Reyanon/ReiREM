// (diag) hash of driver RAM regions — find the frame where device and harness emulation diverge (read only)
static UINT32 s_ram_h;
static INT32 __cdecl RamHashAcb(struct BurnArea *pba)
{
	const UINT8 *p = (const UINT8 *)pba->Data;
	for (UINT32 i = 0; i < pba->nLen; i++)
		s_ram_h = (s_ram_h ^ p[i]) * 16777619u;
	return 0;
}
extern "C" uint32_t rei_core_ram_hash(void)
{
	INT32 (__cdecl *prev)(struct BurnArea *) = BurnAcb;
	BurnAcb = RamHashAcb;
	s_ram_h = 2166136261u;
	pDrv->AreaScan(ACB_MEMORY_RAM | ACB_READ, NULL);
	BurnAcb = prev;
	return s_ram_h;
}

static UINT32 state_scan(UINT8 *buf, UINT32 len, int load)
{
	INT32 (__cdecl *prev)(struct BurnArea *) = BurnAcb;
	BurnAcb = StateAcb;
	s_st_buf = buf;
	s_st_len = len;
	s_st_pos = 0;
	s_st_load = load;
	pDrv->AreaScan(ACB_FULLSCAN | (load ? ACB_WRITE : ACB_READ), NULL);
	BurnStateMAMEScan(ACB_FULLSCAN | (load ? ACB_WRITE : ACB_READ), NULL); // (like burn.cpp BurnAreaScan: fm.c and other MAME chip state)
	BurnAcb = prev;
	s_st_buf = NULL;
	return s_st_pos;
}

extern "C" int rei_core_state_save(const char *path)
{
	struct rei_state_header h;
	memset(&h, 0, sizeof(h));
	h.magic = REI_STATE_MAGIC;
	h.version = REI_STATE_VERSION;
	strncpy(h.set, pDrv->szShortName, sizeof(h.set) - 1);
	h.scan_len = state_scan(NULL, 0, 0);
	h.pipe_len = (UINT32)pipe_state_size();
	// In-game quicksave: wait until the sound thread finishes this frame (incl. audio mix) and idles (usually a few ms)
	for (int spin = 0; !pipe_synced() && spin < 200000000; spin++)
		if (rei_wait_hook) rei_wait_hook();
	if (!pipe_synced())
		return -2;
	UINT8 *buf = (UINT8 *)malloc(h.scan_len + h.pipe_len);
	if (!buf)
		return -1;
	memset(buf, 0, h.scan_len + h.pipe_len);
	if ((s_is_m107 ? rei_m107_pipe_state_save(buf + h.scan_len) : rei_m92_pipe_state_save(buf + h.scan_len)) != 0) {
		free(buf);
		return -2; // pipeline not aligned at a frame boundary
	}
	state_scan(buf, h.scan_len, 0);
	FILE *f = fopen(path, "wb");
	int ok = f && fwrite(&h, sizeof(h), 1, f) == 1 && fwrite(buf, 1, h.scan_len + h.pipe_len, f) == h.scan_len + h.pipe_len;
	if (f)
		fclose(f);
	free(buf);
	return ok ? 0 : -1;
}

// In thread mode, call after stopping the sound/render threads (same as reset)
extern "C" int rei_core_state_load(const char *path)
{
	FILE *f = fopen(path, "rb");
	if (!f)
		return -1;
	struct rei_state_header h;
	int ok = fread(&h, sizeof(h), 1, f) == 1 && h.magic == REI_STATE_MAGIC && h.version == REI_STATE_VERSION &&
		!strncmp(h.set, pDrv->szShortName, sizeof(h.set)) && h.scan_len == state_scan(NULL, 0, 0) &&
		h.pipe_len == (UINT32)pipe_state_size();
	UINT8 *buf = ok ? (UINT8 *)malloc(h.scan_len + h.pipe_len) : NULL;
	ok = ok && buf && fread(buf, 1, h.scan_len + h.pipe_len, f) == h.scan_len + h.pipe_len;
	fclose(f);
	if (ok) {
		state_scan(buf, h.scan_len, 1);
		if (s_is_m107)
			rei_m107_pipe_state_load(buf + h.scan_len);
		else
			rei_m92_pipe_state_load(buf + h.scan_len);
		rei_defer_reset();
		if (pDrv->pRecalcPal)
			*pDrv->pRecalcPal = 1;
		REI_SH(rei_stop) = 0;
	}
	free(buf);
	return ok ? 0 : -1;
}

extern "C" int rei_core_state_exists(const char *path)
{
	FILE *f = fopen(path, "rb");
	if (!f)
		return 0;
	fclose(f);
	return 1;
}

