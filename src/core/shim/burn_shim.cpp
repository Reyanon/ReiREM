extern "C" int rei_core_cheats_load(const char *dir)
{
	// if the sound side runs on another thread (Vita CPU1, PSP ME), write main CPU memory only
	return rei_cheats_load(dir, pDrv->szShortName, pDrv->szParent, rei_threaded);
}

// If all cheats are off, RAM is untouched (no hash impact)
static void cheat_hook()
{
	if (!s_cheats_ok || (s_start_stage <= 0 && !s_inf_health)) {
		s_mode_prev = 0;
		return;
	}
	VezOpen(0);
	const int mode = VezReadByte(REI_RAM_GAME_MODE);
	if (s_start_stage > 0) {
		if (s_mode_prev == 3 && mode == 4)
			s_stage_hold = 30;
		if (mode != 4)
			s_stage_hold = 0;
		if (s_stage_hold > 0) {
			VezWriteByte(REI_RAM_STAGE, (UINT8)s_start_stage);
			s_stage_hold--;
		}
	}
	if (s_inf_health && mode == 5 && VezReadByte(REI_RAM_P1_HEALTH) < REI_P1_HEALTH_MAX)
		VezWriteByte(REI_RAM_P1_HEALTH, REI_P1_HEALTH_MAX);
	VezClose();
	s_mode_prev = mode;
}

