int rei_trace_frame;
#endif
extern "C" void rei_core_run_frame(void *fb, int pitch_bytes, int16_t *audio)
{
#ifdef REI_TIMER_TRACE
	rei_trace_frame++;
#endif
	if (!rei_defer_on) { // (while drawing is deferred, the render thread uses pBurnDraw)
		pBurnDraw = (UINT8 *)fb;
		nBurnPitch = pitch_bytes;
	}
	const int reset_now = s_reset_pending && s_inputs[REI_IN_RESET];
	if (reset_now)
		*s_inputs[REI_IN_RESET] = 1;
	s_reset_pending = 0;
	// In thread mode only the sound thread uses pBurnSoundOut. YM2151 produces no sound if this is NULL at
	// register-write and render time, so main touching it would drop FM.
	if (!rei_threaded)
		pBurnSoundOut = audio;
	REI_PROF_BEGIN(frame);
	if (rei_threaded)
		s_is_m107 ? rei_m107_main_frame() : rei_m92_main_frame(); // the sound side is handled by the thread running rei_core_sound_frame()
	else
		pDrv->Frame();
#ifdef REI_YM_ME
	if (s_ym_me && !rei_threaded) BurnYM2151MeFrameEnd(audio, nBurnSoundLen); // (replaced with the previous frame's sound)
#endif
	REI_PROF_END(frame, REI_PROF_FRAME);
	if (reset_now)
		*s_inputs[REI_IN_RESET] = 0;
	cheat_hook();
	rei_cheats_apply();
	nCurrentFrame++;
	nFramesEmulated++;
}

