// Start stage select (not a DIP feature. Addresses found by harness RAM analysis, 2026-10-09)
//   0xe422c game state: 1 attract, 2 credit, 3 player select, 4 stage start, 5 play, 6 continue, 8 game over
//   0xe2546 stage number: 0 Seattle ~ 6 New York (7-12 are demo scenes)
// When the select screen ends (3→4) the game writes 0 to the stage number and loads the stage from it within ~50 frames.
// The chosen number is written in that window (30 frames after 3→4). Continue/next stage skip 3→4, so they are unaffected.
// 1P health 0xe44a4: 100 at game start, drops when hit, a life is lost at 0 (0xe41a4 is a display copy one frame behind).
// Infinite health restores 100 whenever it drops below 100 during play (state 5). Getting knocked down still happens.
#define REI_RAM_GAME_MODE 0xe422c
#define REI_RAM_STAGE     0xe2546
#define REI_RAM_P1_HEALTH 0xe44a4
#define REI_P1_HEALTH_MAX 100
static int s_start_stage, s_mode_prev, s_stage_hold, s_inf_health;

extern "C" void rei_core_set_start_stage(int stage)
{
	s_start_stage = (stage >= 0 && stage < REI_STAGE_COUNT) ? stage : 0;
}

extern "C" void rei_core_set_infinite_health(int on)
{
	s_inf_health = on ? 1 : 0;
}

