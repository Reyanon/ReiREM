// Displayed title: strip FBNeo's "uncertain" question marks ("(bootleg?)", "(Korea?)") (original driver strings unchanged)
static const char *clean_title(const BurnDriver *d, char *buf, int n)
{
	const char *t = d->szFullNameA ? d->szFullNameA : d->szShortName;
	int k = 0;
	for (; *t && k < n - 1; t++)
		if (*t != '?')
			buf[k++] = *t;
	buf[k] = 0;
	return buf;
}
extern "C" const char *rei_core_game_title(int i)
{
	static char titles[REI_NDRIVERS + REI_NMETA][96];
	if (i < 0 || i >= REI_NDRIVERS + REI_NMETA)
		return "";
	if (!titles[i][0]) {
		if (const rei_meta_entry *m = meta_of(i)) {
			int k = 0;
			for (const char *t = m->title; *t && k < (int)sizeof(titles[i]) - 1; t++)
				if (*t != '?')
					titles[i][k++] = *t;
		} else
			clean_title(s_drivers[i].drv, titles[i], sizeof(titles[i]));
	}
	return titles[i];
}

