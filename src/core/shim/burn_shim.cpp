// PC histogram (REI_PCHIST, for PC harness analysis)

#ifdef REI_PCHIST
static UINT32 *s_pchist[2];
static UINT32 *s_pccount; // V33 execution counts (M6 recompile coverage)

// clear what has been collected so far (to look at a specific section only)
extern "C" void rei_core_pchist_reset(void)
{
	for (int c = 0; c < 2; c++)
		if (s_pchist[c]) memset(s_pchist[c], 0, (1 << 20) * sizeof(UINT32));
	if (s_pccount) memset(s_pccount, 0, (1 << 20) * sizeof(UINT32));
}

extern "C" void rei_pchist_add(int cpu, unsigned pc, int cycles)
{
	if (!s_pchist[cpu])
		s_pchist[cpu] = (UINT32 *)calloc(1 << 20, sizeof(UINT32));
	s_pchist[cpu][pc & 0xFFFFF] += (UINT32)cycles;
	if (cpu == 0) {
		if (!s_pccount)
			s_pccount = (UINT32 *)calloc(1 << 20, sizeof(UINT32));
		s_pccount[pc & 0xFFFFF]++;
	}
}
#endif

// M6 recompile input: V33 coverage (executed instruction start addresses and counts) and an image of V33 address space 0x00000-0x9ffff.
// Derived from the ROM, so generated only on the user's PC and never committed (docs/RULES.md ch. 6 rule 1).
extern "C" int rei_core_cover_dump(const char *cover_path, const char *image_path)
{
#ifdef REI_PCHIST
	if (!s_pccount)
		return -1;
	FILE *f = fopen(cover_path, "w");
	if (!f)
		return -1;
	for (int i = 0; i < (1 << 20); i++)
		if (s_pccount[i])
			fprintf(f, "%05x %u\n", i, s_pccount[i]);
	fclose(f);
	f = fopen(image_path, "wb");
	if (!f)
		return -1;
	VezOpen(0);
	for (UINT32 a = 0; a < 0xa0000; a++)
		fputc(VezReadByte(a), f);
	VezClose();
	fclose(f);
	return 0;
#else
	(void)cover_path;
	(void)image_path;
	return -1;
#endif
}

extern "C" int rei_core_pchist_dump(const char *path, int top)
{
#ifdef REI_PCHIST
	FILE *f = fopen(path, "w");
	if (!f)
		return -1;
	// REI_PCHIST_COUNT: V33 uses execution counts instead of cycles (on PSP interpretation cost scales with instruction count, not cycles)
	const int count = getenv("REI_PCHIST_COUNT") != NULL;
	for (int cpu = 0; cpu < 2; cpu++) {
		UINT32 *h = (cpu == 0 && count) ? s_pccount : s_pchist[cpu];
		if (!h)
			continue;
		UINT64 total = 0;
		for (int i = 0; i < (1 << 20); i++)
			total += h[i];
		fprintf(f, "# cpu %d (%s) total %s %llu\n", cpu, cpu ? "V35" : "V33", (cpu == 0 && count) ? "instructions" : "cycles",
			(unsigned long long)total);
		// simple selection of the top entries (analysis only, speed irrelevant)
		for (int k = 0; k < top; k++) {
			int best = -1;
			for (int i = 0; i < (1 << 20); i++)
				if (h[i] && (best < 0 || h[i] > h[best]))
					best = i;
			if (best < 0)
				break;
			fprintf(f, "%05x %10u %6.2f%%\n", best, h[best], 100.0 * h[best] / (double)total);
			h[best] = 0;
		}
	}
	fclose(f);
	return 0;
#else
	(void)path;
	(void)top;
	return -1;
#endif
}

