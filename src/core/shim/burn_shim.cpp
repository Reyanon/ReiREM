extern "C" int rei_core_prof_take(uint64_t *out, int max)
{
#ifdef REI_PROFILE
	int n = max < REI_PROF_COUNT ? max : REI_PROF_COUNT;
#ifdef REI_ME_SPLIT
	// the Media Engine adds to its slots concurrently: never write them from here (a clear inside the ME's
	// read-modify-write would be undone), return the growth since the last call instead
	static uint64_t last[REI_PROF_COUNT];
	for (int i = 0; i < n; i++) {
		uint64_t v = REI_PROF_ACC[i];
		out[i] = v - last[i];
		last[i] = v;
	}
#else
	for (int i = 0; i < n; i++) {
		out[i] = REI_PROF_ACC[i];
		REI_PROF_ACC[i] = 0;
	}
#endif
	return n;
#else
	(void)out;
	(void)max;
	return 0;
#endif
}

