static INT32 __cdecl ZipLoadRom(UINT8 *Dest, INT32 *pnWrote, INT32 i)
{
	struct BurnRomInfo ri;
	char *name = NULL;
	BurnDrvGetRomInfo(&ri, i);
	BurnDrvGetRomName(&name, i, 0);

	// ROMs missing from the clone zip (split sets) are looked up in the parent zip
	rei_zip *z = s_zip;
	int idx = rei_zip_find(z, name, ri.nCrc);
	if (idx < 0 && s_parent_zip) {
		z = s_parent_zip;
		idx = rei_zip_find(z, name, ri.nCrc);
	}
	if (idx < 0) {
		snprintf(s_error, sizeof(s_error), "ROM missing: %s (crc %08x)", name ? name : "?", ri.nCrc);
		return 1;
	}
	// error text goes straight to the Vita screen (default PGF font, ASCII only), so keep it in English
	if (rei_zip_entry_crc(z, idx) != ri.nCrc) {
		snprintf(s_error, sizeof(s_error), "ROM CRC mismatch: %s (%08x, expected %08x)",
			name ? name : "?", rei_zip_entry_crc(z, idx), ri.nCrc);
		return 1;
	}

	uint32_t got = 0;
	if (rei_zip_read(z, idx, Dest, ri.nLen, &got) != 0) {
		snprintf(s_error, sizeof(s_error), "ROM unzip failed: %s", name ? name : "?");
		return 1;
	}
	if (pnWrote)
		*pnWrote = (INT32)got;
	return 0;
}

