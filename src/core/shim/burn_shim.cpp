// Apply DIP defaults the same way as FBNeo burner's InpDIPSWResetDIPs
static void apply_default_dips()
{
	struct BurnDIPInfo bdi;
	INT32 nOffset = 0;
	for (UINT32 i = 0; BurnDrvGetDIPInfo(&bdi, i) == 0; i++) {
		if (bdi.nFlags == 0xF0) {
			nOffset = bdi.nInput;
			break;
		}
	}
	for (UINT32 i = 0; BurnDrvGetDIPInfo(&bdi, i) == 0; i++) {
		if (bdi.nFlags != 0xFF)
			continue;
		struct BurnInputInfo bii;
		if (BurnDrvGetInputInfo(&bii, bdi.nInput + nOffset) != 0 || bii.pVal == NULL)
			continue;
		*bii.pVal = (*bii.pVal & ~bdi.nMask) | (bdi.nSetting & bdi.nMask);
	}
}

