INT32 __cdecl ZipLoadOneFile(char *arcName, const char *fileName, void **Dest, INT32 *pnWrote)
{
	char p[MAX_PATH + 8];
	snprintf(p, sizeof(p), "%s%s", arcName, strstr(arcName, ".zip") ? "" : ".zip");
	*Dest = NULL;
	*pnWrote = 0;
	rei_zip *z = rei_zip_open(p);
	if (!z)
		return 1;
	const int idx = rei_zip_find(z, fileName, 0);
	if (idx >= 0) {
		const uint32_t len = rei_zip_entry_size(z, idx);
		uint8_t *buf = (uint8_t *)malloc(len ? len : 1); // freed by samples.cpp
		uint32_t got = 0;
		if (buf && rei_zip_read(z, idx, buf, len, &got) == 0) {
			*Dest = buf;
			*pnWrote = (INT32)got;
		} else {
			free(buf);
		}
	}
	rei_zip_close(z);
	return *Dest ? 0 : 1;
}
