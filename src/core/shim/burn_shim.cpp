// DIP switches (FBNeo BurnDIPInfo format: 0xFF default, 0xFE group header (nSetting = number of options), then the options)

#define REI_DIP_MAX_GROUPS 16
#define REI_DIP_MAX_OPTS   20
struct rei_dip_group {
	const char *name;
	UINT8 *val;          // DIP input byte
	int nopts;
	UINT8 mask[REI_DIP_MAX_OPTS], set[REI_DIP_MAX_OPTS];
	const char *opt[REI_DIP_MAX_OPTS];
};
static struct rei_dip_group s_dips[REI_DIP_MAX_GROUPS];
static int s_ndips;

static UINT8 *dip_input(INT32 nInput)
{
	struct BurnInputInfo bii;
	if (BurnDrvGetInputInfo(&bii, nInput) != 0)
		return NULL;
	return bii.pVal;
}

static void parse_dips()
{
	s_ndips = 0;
	struct BurnDIPInfo bdi;
	struct rei_dip_group *g = NULL;
	int left = 0;
	// Add the DIP_OFFSET (0xF0) entry to input numbers if present (same as apply_default_dips. Hook etc. use 0x22 — without it the coin/start
	// input bytes were changed instead of the DIPs)
	INT32 nOffset = 0;
	for (UINT32 i = 0; BurnDrvGetDIPInfo(&bdi, i) == 0; i++)
		if (bdi.nFlags == 0xF0) {
			nOffset = bdi.nInput;
			break;
		}
	for (UINT32 i = 0; BurnDrvGetDIPInfo(&bdi, i) == 0; i++) {
		if (bdi.nFlags == 0xF0)
			continue;
		if (bdi.nFlags == 0xFE || bdi.nFlags == 0xFD) {
			g = NULL;
			left = bdi.nSetting;
			// items that change emulator internals (HACK) aren't game settings, so hide them
			if (!bdi.szText || strstr(bdi.szText, "HACK") || s_ndips >= REI_DIP_MAX_GROUPS)
				continue;
			g = &s_dips[s_ndips++];
			g->name = bdi.szText;
			g->val = NULL;
			g->nopts = 0;
		} else if (left > 0) {
			left--;
			if (!g || g->nopts >= REI_DIP_MAX_OPTS)
				continue;
			UINT8 *v = dip_input(bdi.nInput + nOffset);
			if (!v)
				continue;
			g->val = v;
			g->mask[g->nopts] = bdi.nMask;
			g->set[g->nopts] = bdi.nSetting;
			g->opt[g->nopts] = bdi.szText;
			g->nopts++;
		}
	}
}

extern "C" int rei_core_dip_count(void) { return s_ndips; }
extern "C" const char *rei_core_dip_name(int g) { return (g >= 0 && g < s_ndips) ? s_dips[g].name : ""; }
extern "C" int rei_core_dip_options(int g) { return (g >= 0 && g < s_ndips) ? s_dips[g].nopts : 0; }

extern "C" const char *rei_core_dip_option_name(int g, int o)
{
	if (g < 0 || g >= s_ndips || o < 0 || o >= s_dips[g].nopts)
		return "";
	return s_dips[g].opt[o];
}

extern "C" int rei_core_dip_get(int g)
{
	if (g < 0 || g >= s_ndips || !s_dips[g].val)
		return -1;
	const struct rei_dip_group *d = &s_dips[g];
	for (int o = 0; o < d->nopts; o++)
		if ((*d->val & d->mask[o]) == (d->set[o] & d->mask[o]))
			return o;
	return -1;
}

extern "C" void rei_core_dip_set(int g, int o)
{
	if (g < 0 || g >= s_ndips || o < 0 || o >= s_dips[g].nopts || !s_dips[g].val)
		return;
	struct rei_dip_group *d = &s_dips[g];
	*d->val = (*d->val & ~d->mask[o]) | (d->set[o] & d->mask[o]);
}

extern "C" void rei_core_dip_defaults(void)
{
	apply_default_dips();
}

// DIP input bytes (for saving settings). Bytes used by groups, in order, without duplicates
extern "C" int rei_core_dip_raw(uint8_t *out, int max)
{
	UINT8 *seen[REI_DIP_MAX_GROUPS];
	int n = 0;
	for (int g = 0; g < s_ndips && n < max; g++) {
		int dup = 0;
		for (int k = 0; k < n; k++)
			dup |= (seen[k] == s_dips[g].val);
		if (!dup && s_dips[g].val) {
			seen[n] = s_dips[g].val;
			out[n++] = *s_dips[g].val;
		}
	}
	return n;
}

extern "C" void rei_core_dip_set_raw(const uint8_t *in, int count)
{
	UINT8 *seen[REI_DIP_MAX_GROUPS];
	int n = 0;
	for (int g = 0; g < s_ndips && n < count; g++) {
		int dup = 0;
		for (int k = 0; k < n; k++)
			dup |= (seen[k] == s_dips[g].val);
		if (dup || !s_dips[g].val)
			continue;
		seen[n] = s_dips[g].val;
		// change only the group's bits so bytes shared with hidden (HACK) items stay intact
		UINT8 m = 0;
		for (int h = 0; h < s_ndips; h++)
			if (s_dips[h].val == s_dips[g].val)
				for (int o = 0; o < s_dips[h].nopts; o++)
					m |= s_dips[h].mask[o];
		*s_dips[g].val = (*s_dips[g].val & ~m) | (in[n] & m);
		n++;
	}
}

