#!/usr/bin/env python3
"""Pre-render the PSP menu font into a bitmap atlas (psp/src/font_ui.c).

Source: psp/font/NotoSans-Regular.ttf (Noto Sans, SIL Open Font License 1.1, psp/font/OFL.txt). The glyphs are drawn with
FreeType hinting at the exact pixel sizes the UI uses (no scaling on the PSP: sharp text), so the output is a Modified Version
of the font under the OFL: it is distributed under the same license and named "ReiREM UI" (derived from Noto Sans).

Output: one 8-bit alpha atlas (the GE draws it as a T8 texture with a white CLUT ramp) and per size a glyph table for
U+0020..U+00FF (ASCII and Latin-1: everything the UI prints, game titles included).
Usage (Pillow): python psp/tools/make_font.py
"""
import math
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "psp", "font", "NotoSans-Regular.ttf")
OUT = os.path.join(ROOT, "psp", "src", "font_ui.c")
SIZES = [11, 12, 13]  # px: button help / tabs and notes / titles, list and menu rows (ui.c font_size)
FIRST, LAST = 0x20, 0xFF
ATLAS_W = 512
STAR = 11  # px: the favourites star (five points, anti-aliased, drawn like a glyph)
PILL_W, PILL_H, KNOB = 28, 14, 10  # px: on/off switch track and knob (ui_toggle)


def main():
    glyphs = []  # per size: list of (code, bitmap, xoff, yoff, adv)
    metrics = []
    for px in SIZES:
        f = ImageFont.truetype(SRC, px)
        asc, desc = f.getmetrics()
        metrics.append((asc, desc))
        gs = []
        for code in range(FIRST, LAST + 1):
            ch = chr(code)
            if 0x7F <= code < 0xA0:
                gs.append((code, None, 0, 0, 0))
                continue
            adv = int(round(f.getlength(ch)))
            box = f.getbbox(ch, anchor="ls")  # relative to the pen on the baseline
            w, h = box[2] - box[0], box[3] - box[1]
            if w <= 0 or h <= 0:
                gs.append((code, None, 0, 0, adv))
                continue
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255, anchor="ls")
            gs.append((code, im, box[0], box[1], adv))
        glyphs.append(gs)

    # the favourites star: drawn 8x larger and box-filtered down (the GE does not anti-alias; a polygon this small was ragged)
    ss = 8
    big = Image.new("L", (STAR * ss, STAR * ss), 0)
    c, ro = STAR * ss / 2.0, STAR * ss / 2.0 - ss * 0.3
    pts = []
    for k in range(10):
        a = -math.pi / 2 + k * math.pi / 5
        r = ro if k % 2 == 0 else ro * 0.45
        pts.append((c + r * math.cos(a), c + r * math.sin(a) + ss * 0.4))
    ImageDraw.Draw(big).polygon(pts, fill=255)
    shapes = [(-1, big.resize((STAR, STAR), Image.BOX), 0, 0, 0)]
    # switch track (a pill) and knob (a disc), same supersampling
    big = Image.new("L", (PILL_W * ss, PILL_H * ss), 0)
    ImageDraw.Draw(big).rounded_rectangle((0, 0, PILL_W * ss - 1, PILL_H * ss - 1), radius=PILL_H * ss // 2, fill=255)
    shapes.append((-2, big.resize((PILL_W, PILL_H), Image.BOX), 0, 0, 0))
    big = Image.new("L", (KNOB * ss, KNOB * ss), 0)
    ImageDraw.Draw(big).ellipse((0, 0, KNOB * ss - 1, KNOB * ss - 1), fill=255)
    shapes.append((-3, big.resize((KNOB, KNOB), Image.BOX), 0, 0, 0))
    glyphs.append(shapes)

    # shelf packing, one pixel between glyphs
    x = y = shelf = 0
    place = {}
    for si, gs in enumerate(glyphs):
        for code, im, _, _, _ in gs:
            if im is None:
                continue
            w, h = im.size
            if x + w > ATLAS_W:
                x, y, shelf = 0, y + shelf + 1, 0
            place[(si, code)] = (x, y)
            x += w + 1
            shelf = max(shelf, h)
    height = y + shelf
    atlas_h = 1
    while atlas_h < height:
        atlas_h <<= 1
    rows = (height + 15) & ~15  # (stored rows; the GE texture height is the power of two above)
    atlas = Image.new("L", (ATLAS_W, rows), 0)
    for si, gs in enumerate(glyphs):
        for code, im, _, _, _ in gs:
            if im is not None:
                atlas.paste(im, place[(si, code)])

    px_data = atlas.tobytes()
    out = []
    out.append("// Generated by psp/tools/make_font.py - do not edit.\n")
    out.append("// \"ReiREM UI\" bitmap font: Noto Sans Regular pre-rendered at %s px (U+0020..U+00FF).\n"
               % ", ".join(str(s) for s in SIZES))
    out.append("// Copyright 2022 The Noto Project Authors (https://github.com/notofonts/latin-greek-cyrillic).\n")
    out.append("// Licensed under the SIL Open Font License, Version 1.1: psp/font/OFL.txt (this bitmap is a Modified Version).\n")
    out.append('#include "font_ui.h"\n\n')
    out.append("const rei_font_size rei_font_sizes[REI_FONT_SIZES] = {\n")
    for px, (asc, desc) in zip(SIZES, metrics):
        out.append("\t{ %d, %d, %d },\n" % (px, asc, desc))
    out.append("};\n\n")
    out.append("const rei_font_glyph rei_font_glyphs[REI_FONT_SIZES][REI_FONT_COUNT] = {\n")
    for si, gs in enumerate(glyphs[:len(SIZES)]):
        out.append("\t{\n")
        for code, im, xo, yo, adv in gs:
            if im is None:
                out.append("\t\t{ 0, 0, 0, 0, 0, 0, %d },\n" % adv)
            else:
                u, v = place[(si, code)]
                out.append("\t\t{ %d, %d, %d, %d, %d, %d, %d },\n" % (u, v, im.size[0], im.size[1], xo, yo, adv))
        out.append("\t},\n")
    out.append("};\n\n")
    for code, name, w, h in ((-1, "star", STAR, STAR), (-2, "pill", PILL_W, PILL_H), (-3, "knob", KNOB, KNOB)):
        su, sv = place[(len(SIZES), code)]
        out.append("const rei_font_glyph rei_font_%s = { %d, %d, %d, %d, %d, %d, 0 };\n" % (name, su, sv, w, h, -(w // 2), -(h // 2)))
    out.append("\n")
    out.append("const uint8_t rei_font_atlas[REI_FONT_ATLAS_W * REI_FONT_ATLAS_ROWS] __attribute__((aligned(16))) = {\n")
    for i in range(0, len(px_data), 32):
        out.append("\t" + ",".join(str(b) for b in px_data[i:i + 32]) + ",\n")
    out.append("};\n")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("".join(out))
    hdr = os.path.join(ROOT, "psp", "src", "font_ui.h")
    with open(hdr, "w", newline="\n") as fh:
        fh.write(
            "// Generated by psp/tools/make_font.py - do not edit. Bitmap font \"ReiREM UI\" (from Noto Sans, SIL OFL 1.1: psp/font/OFL.txt)\n"
            "#ifndef REI_PSP_FONT_UI_H\n#define REI_PSP_FONT_UI_H\n\n#include <stdint.h>\n\n"
            "#define REI_FONT_SIZES %d\n#define REI_FONT_FIRST 0x%02X\n#define REI_FONT_COUNT %d\n"
            "#define REI_FONT_ATLAS_W %d\n#define REI_FONT_ATLAS_H %d\n#define REI_FONT_ATLAS_ROWS %d\n\n"
            "typedef struct { uint8_t px, ascent, descent; } rei_font_size;\n"
            "// atlas position and size, offset of the bitmap from the pen on the baseline, advance (px)\n"
            "typedef struct { uint16_t u, v; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; } rei_font_glyph;\n\n"
            "extern const rei_font_size rei_font_sizes[REI_FONT_SIZES];\n"
            "extern const rei_font_glyph rei_font_glyphs[REI_FONT_SIZES][REI_FONT_COUNT];\n"
            "// shapes, anti-aliased (offsets centre them on the point given): favourites star, switch track and knob\n"
            "extern const rei_font_glyph rei_font_star, rei_font_pill, rei_font_knob;\n"
            "extern const uint8_t rei_font_atlas[REI_FONT_ATLAS_W * REI_FONT_ATLAS_ROWS];\n\n#endif\n"
            % (len(SIZES), FIRST, LAST - FIRST + 1, ATLAS_W, atlas_h, rows))
    print("atlas %dx%d (used %d rows), %d sizes" % (ATLAS_W, atlas_h, height, len(SIZES)))


if __name__ == "__main__":
    main()
